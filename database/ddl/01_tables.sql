-- Generic lookup values (categories, statuses, countries, roles)
create table vom_lookups (
  lookup_type   varchar2(30)  not null,
  code          varchar2(30)  not null,
  meaning       varchar2(200) not null,
  display_seq   number(4)     default 10 not null,
  active_yn     varchar2(1)   default 'Y' not null,
  constraint vom_lookups_pk primary key (lookup_type, code),
  constraint vom_lookups_active_ck check (active_yn in ('Y','N'))
);

-- Application users and their roles (drives APEX authorization schemes)
create table vom_user_roles (
  username      varchar2(255) not null,
  role_code     varchar2(30)  not null,
  granted_on    date          default sysdate not null,
  granted_by    varchar2(255),
  constraint vom_user_roles_pk primary key (username, role_code)
);

create table vom_vendors (
  vendor_id             number generated by default on null as identity,
  vendor_number         varchar2(20),
  vendor_name           varchar2(200) not null,
  tax_registration_no   varchar2(50),
  country_code          varchar2(2)   not null,
  category_code         varchar2(30)  not null,
  annual_spend_band     varchar2(30),
  website               varchar2(255),
  primary_contact_name  varchar2(200),
  primary_email         varchar2(255) not null,
  phone                 varchar2(50),
  status                varchar2(20)  default 'DRAFT' not null,
  risk_score            number(5,2),
  risk_level            varchar2(10),
  risk_calculated_on    date,
  approved_on           date,
  created_by            varchar2(255) not null,
  created_on            date          default sysdate not null,
  updated_by            varchar2(255),
  updated_on            date,
  constraint vom_vendors_pk primary key (vendor_id),
  constraint vom_vendors_number_uk unique (vendor_number),
  constraint vom_vendors_tax_uk unique (country_code, tax_registration_no),
  constraint vom_vendors_status_ck check (status in
    ('DRAFT','SUBMITTED','UNDER_REVIEW','APPROVED','REJECTED','SUSPENDED')),
  constraint vom_vendors_risk_ck check (risk_level in ('LOW','MEDIUM','HIGH')),
  constraint vom_vendors_email_ck check (regexp_like(primary_email,
    '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'))
);

create table vom_vendor_contacts (
  contact_id    number generated by default on null as identity,
  vendor_id     number        not null,
  contact_name  varchar2(200) not null,
  job_title     varchar2(100),
  email         varchar2(255) not null,
  phone         varchar2(50),
  primary_yn    varchar2(1)   default 'N' not null,
  constraint vom_contacts_pk primary key (contact_id),
  constraint vom_contacts_vendor_fk foreign key (vendor_id)
    references vom_vendors (vendor_id) on delete cascade,
  constraint vom_contacts_primary_ck check (primary_yn in ('Y','N'))
);

-- Which compliance documents exist, which are mandatory, how long they stay valid
create table vom_document_types (
  doc_type_code    varchar2(30)  not null,
  doc_type_name    varchar2(200) not null,
  mandatory_yn     varchar2(1)   default 'Y' not null,
  validity_months  number(3),
  category_code    varchar2(30),            -- null = applies to every category
  constraint vom_doc_types_pk primary key (doc_type_code),
  constraint vom_doc_types_mand_ck check (mandatory_yn in ('Y','N'))
);

create table vom_vendor_documents (
  doc_id          number generated by default on null as identity,
  vendor_id       number        not null,
  doc_type_code   varchar2(30)  not null,
  file_name       varchar2(400) not null,
  mime_type       varchar2(255) not null,
  file_blob       blob,
  issued_on       date,
  expires_on      date,
  status          varchar2(20)  default 'PENDING' not null,
  verified_by     varchar2(255),
  verified_on     date,
  uploaded_by     varchar2(255) not null,
  uploaded_on     date          default sysdate not null,
  constraint vom_documents_pk primary key (doc_id),
  constraint vom_documents_vendor_fk foreign key (vendor_id)
    references vom_vendors (vendor_id) on delete cascade,
  constraint vom_documents_type_fk foreign key (doc_type_code)
    references vom_document_types (doc_type_code),
  constraint vom_documents_status_ck check (status in
    ('PENDING','VALID','EXPIRING','EXPIRED','REJECTED')),
  constraint vom_documents_dates_ck check (expires_on is null or issued_on is null
    or expires_on > issued_on)
);

-- Weighted risk factors; weights are configurable by administrators
create table vom_risk_factors (
  factor_code   varchar2(30)  not null,
  description   varchar2(400) not null,
  weight        number(5,2)   not null,
  active_yn     varchar2(1)   default 'Y' not null,
  constraint vom_risk_factors_pk primary key (factor_code),
  constraint vom_risk_factors_weight_ck check (weight between 0 and 100)
);

create table vom_vendor_risk (
  vendor_id     number        not null,
  factor_code   varchar2(30)  not null,
  score         number(5,2)   not null,
  notes         varchar2(400),
  constraint vom_vendor_risk_pk primary key (vendor_id, factor_code),
  constraint vom_vendor_risk_vendor_fk foreign key (vendor_id)
    references vom_vendors (vendor_id) on delete cascade,
  constraint vom_vendor_risk_factor_fk foreign key (factor_code)
    references vom_risk_factors (factor_code)
);

-- Approval chain per risk level (configuration, not code)
create table vom_approval_rules (
  rule_id        number generated by default on null as identity,
  risk_level     varchar2(10)  not null,
  step_seq       number(2)     not null,
  approver_role  varchar2(30)  not null,
  constraint vom_approval_rules_pk primary key (rule_id),
  constraint vom_approval_rules_uk unique (risk_level, step_seq),
  constraint vom_approval_rules_risk_ck check (risk_level in ('LOW','MEDIUM','HIGH'))
);

create table vom_approval_steps (
  step_id        number generated by default on null as identity,
  vendor_id      number        not null,
  step_seq       number(2)     not null,
  approver_role  varchar2(30)  not null,
  status         varchar2(20)  default 'PENDING' not null,
  decided_by     varchar2(255),
  decided_on     date,
  comments       varchar2(4000),
  created_on     date          default sysdate not null,
  constraint vom_approval_steps_pk primary key (step_id),
  constraint vom_approval_steps_vendor_fk foreign key (vendor_id)
    references vom_vendors (vendor_id) on delete cascade,
  constraint vom_approval_steps_status_ck check (status in
    ('WAITING','PENDING','APPROVED','REJECTED','CANCELLED'))
);

create table vom_audit_log (
  audit_id       number generated by default on null as identity,
  entity_name    varchar2(30)  not null,
  entity_id      number        not null,
  action         varchar2(30)  not null,
  old_value      varchar2(200),
  new_value      varchar2(200),
  details        varchar2(4000),
  performed_by   varchar2(255) not null,
  performed_on   timestamp     default systimestamp not null,
  constraint vom_audit_log_pk primary key (audit_id)
);
